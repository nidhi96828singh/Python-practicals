t = (10, 20, 30, 40, 50, 20)
print("Tuple:", t)
print("Length:", len(t))
print("First / last:", t[0], t[-1])
print("Slice [1:4]:", t[1:4])
print("Reversed:", t[::-1])
print("Count of 20:", t.count(20))
print("Index of 30:", t.index(30))
print("Max / Min:", max(t), min(t))
print("Sum:", sum(t))
t2 = (60, 70)
print("Concatenation:", t + t2)
print("Repetition:", t2 * 2)
print("30 in tuple:", 30 in t)
print("As list:", list(t))
print("Sorted:", tuple(sorted(t)))
